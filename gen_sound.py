#!/usr/bin/env python3
# Generates out/sound.s: SOUND on the 1-bit speaker (port 0x12 bit 3), interrupts off.
# A note is a phase accumulator: every sample adds the pitch increment and sends the top bit to
# the speaker. The sample loop is emitted from (instruction, T-states) pairs and must take exactly
# SAMPLE_T; every 256 samples a block ends, and the block's length in centiseconds drives the
# duration and the pitch envelope.
# Copyright (C) 2026 Santiago Crespo
# SPDX-License-Identifier: 0BSD
import sys

CLOCK = 6131790			# CPU clock measured on the unit
SAMPLE_T = 66

TONE = [("add hl, de", 11), ("ld a, h", 4), ("rlca", 4), ("rlca", 4), ("rlca", 4), ("rlca", 4),
        ("and #0x08", 7), ("or c", 4), ("out (0x12), a", 11), ("djnz tl", 13)]
assert sum(t for _, t in TONE) == SAMPLE_T, "tone loop must take %d T-states" % SAMPLE_T

# Fixed part of the block end when no centisecond passes (tone path), counted from the code below
BLOCK_END = [("push hl", 11), ("ld hl, (SFRAC)", 16), ("ld a, #FRAC_LO", 7), ("add a, l", 4), ("ld l, a", 4),
             ("ld a, #FRAC_HI", 7), ("adc a, h", 4), ("ld h, a", 4), ("ld (SFRAC), hl", 16), ("pop hl", 10),
             ("jr nc, tblk", 12), ("ld b, #0", 7)]
BLOCK_T = 256 * SAMPLE_T - 5 + sum(t for _, t in BLOCK_END)	# the last djnz falls through (8 T)
FRAC = round(65536 * BLOCK_T / (CLOCK / 100))	# centiseconds per block, 16-bit fraction
# Once per centisecond "tick" runs (no envelope step): call 17 + RESPUESTA test 89 + duration 68 +
# envelope test 32 + return 74 + the jr into the next block 12 = 292 T-states; spread over the blocks
TICK_T = 17 + 89 + 68 + 32 + 74 + 12
FS = 256 * CLOCK / (BLOCK_T + TICK_T * FRAC / 65536)	# effective samples per second
assert 0 < FRAC < 65536


def inc(p):
    """Phase increment for SOUND pitch p (quarter semitones, 89 = A 440 Hz)."""
    return round(440 * 2 ** ((p - 89) / 48) * 65536 / FS)


TOP = [inc(240 + i) for i in range(48)]	# pitches 240-287; lower octaves are shifted right
assert max(TOP) < 32768

out = sys.argv[1]
area = sys.argv[2] if len(sys.argv) > 2 else "CODE"	# linked into page 1
lines = []
w = lines.append
w("; Generated by gen_sound.py. Do not edit.")
w("; Sample loop %d T-states (fs = %.0f Hz), block of 256 samples = %d T-states = %.4f cs." %
  (SAMPLE_T, FS, BLOCK_T, BLOCK_T / (CLOCK / 100)))
w('\t.include "shared.inc"')
w("\t.area\t%s" % area)
w("FRAC_LO = 0x%02X" % (FRAC & 0xFF))
w("FRAC_HI = 0x%02X" % (FRAC >> 8))
w("""SCH = SND			; parameters written by h_sound
SAMPL = SND+1
SPITCH = SND+3
SDUR = SND+4
SFRAC = SND+6			; state
SLEFT = SND+8
SENV = SND+10
SECNT = SND+12
SESEC = SND+13
SEPN = SND+14
SINC = SND+15
SLFSR = SND+17
SNOUT = SND+19
SCUR = SND+20

; Play SND: channel 0 = noise, 1-3 = tone; amplitude 0 = rest, negative = tone, 1-4 = envelope;
; pitch 0-255; duration in twentieths of a second. Interrupts are off while it plays; the
; RESPUESTA key stops it and sets the Escape flag.
sound::	ld	a, i
	di
	push	af
	ld	hl, (SDUR)		; duration in centiseconds (negative or over 254: 254)
	ld	a, h
	or	a
	jr	z, 1$
	ld	l, #254
1$:	ld	a, l
	cp	#255
	jr	c, 2$
	ld	l, #254
2$:	ld	h, #0
	ld	d, h
	ld	e, l
	add	hl, hl
	add	hl, hl
	add	hl, de
	ld	(SLEFT), hl
	ld	hl, #0
	ld	(SFRAC), hl
	ld	(SENV), hl
	ld	a, (SPITCH)
	ld	(SCUR), a
	ld	hl, (SAMPL)		; envelope 1-4?
	ld	a, h
	or	a
	jr	nz, 3$
	ld	a, l
	dec	a
	cp	#4
	jr	nc, 3$
	ld	l, a
	add	a, a
	add	a, a
	add	a, a
	sub	l
	ld	l, a
	ld	de, #ENVS
	add	hl, de
	ld	(SENV), hl
	ld	a, (hl)			; step length
	and	#0x7F
	jr	nz, 4$
	inc	a
4$:	ld	(SECNT), a
	xor	a
	ld	(SESEC), a
	ld	de, #4
	add	hl, de
	ld	a, (hl)			; PN1
	ld	(SEPN), a
3$:	call	pitchinc
	ld	hl, (SAMPL)
	ld	a, h
	or	l
	jr	nz, 5$
	ld	de, #0			; rest: the phase never moves
5$:	ld	(SINC), de
	ld	a, (P12)
	and	#0x20
	ld	c, a			; the LED stays as it is
	ld	hl, #0xACE1
	ld	(SLFSR), hl
	ld	hl, #0
	ld	a, (SCH)
	and	#3
	jr	z, nblk""")
w("tblk:\t%s\t\t; %d" % BLOCK_END[-1])
w("tl:")
for ins, t in TONE:
    w("\t%s\t\t; %d" % (ins, t))
for ins, t in BLOCK_END[:-1]:
    w("\t%s\t\t; %d" % (ins, t))
w("""	call	tick
	jr	nz, tblk
	jr	send

; Noise: when the phase wraps, a 16-bit LFSR steps and its low bit goes to the speaker
nblk:	ld	b, #0
nl:	add	hl, de
	jr	nc, 2$
	push	hl
	ld	hl, (SLFSR)
	srl	h
	rr	l
	jr	nc, 1$
	ld	a, h
	xor	#0xB4
	ld	h, a
1$:	ld	(SLFSR), hl
	ld	a, l
	rlca
	rlca
	rlca
	and	#0x08
	or	c
	ld	(SNOUT), a
	pop	hl
2$:	ld	a, (SNOUT)
	out	(0x12), a
	djnz	nl
	push	hl
	ld	hl, (SFRAC)
	ld	a, #FRAC_LO
	add	a, l
	ld	l, a
	ld	a, #FRAC_HI
	adc	a, h
	ld	h, a
	ld	(SFRAC), hl
	pop	hl
	jr	nc, nblk
	call	tick
	jr	nz, nblk

send:	ld	a, c			; speaker off, LED as it was
	out	(0x12), a
	pop	af
	ret	po
	ei
	ret

; A centisecond has passed: RESPUESTA, duration, envelope. NZ to go on. Keeps C, HL; may change DE.
tick:	ld	a, #0x80		; RESPUESTA: column 7, row 6
	out	(0x10), a
	nop
	in	a, (0x10)
	push	af
	xor	a
	out	(0x10), a
	pop	af
	bit	6, a
	jr	nz, 1$
	ld	a, (FLAGS)
	or	#0x80
	ld	(FLAGS), a
	xor	a
	ret
1$:	push	hl
	ld	hl, (SLEFT)
	dec	hl
	ld	(SLEFT), hl
	ld	a, h
	or	l
	jr	z, 9$
	ld	hl, (SENV)
	ld	a, h
	or	l
	jr	z, 8$
	ld	a, (SECNT)
	dec	a
	ld	(SECNT), a
	jr	nz, 8$
	ld	a, (hl)			; next step
	and	#0x7F
	jr	nz, 2$
	inc	a
2$:	ld	(SECNT), a
	ld	b, #4			; find a section with steps left (at most one round)
3$:	ld	a, (SEPN)
	or	a
	jr	nz, 5$
	ld	a, (SESEC)
	inc	a
	cp	#3
	jr	c, 4$
	bit	7, (hl)			; no repeat: hold the pitch
	jr	nz, 8$
	xor	a
4$:	ld	(SESEC), a
	push	hl
	add	a, #4
	ld	e, a
	ld	d, #0
	add	hl, de
	ld	a, (hl)
	pop	hl
	ld	(SEPN), a
	djnz	3$
	jr	8$
5$:	dec	a
	ld	(SEPN), a
	ld	a, (SESEC)
	inc	a
	ld	e, a
	ld	d, #0
	push	hl
	add	hl, de
	ld	a, (SCUR)
	add	a, (hl)
	ld	(SCUR), a
	pop	hl
	call	pitchinc
	ld	hl, (SAMPL)
	ld	a, h
	or	l
	jr	z, 8$
	ld	(SINC), de
8$:	ld	de, (SINC)
	pop	hl
	ld	b, #0
	or	#1
	ret
9$:	pop	hl
	xor	a
	ret

; DE = phase increment for pitch (SCUR); channel 0 uses the noise rates
pitchinc:
	ld	a, (SCH)
	and	#3
	jr	nz, 1$
	ld	a, (SCUR)
	and	#3
	add	a, a
	ld	e, a
	ld	d, #0
	ld	hl, #nrate
	add	hl, de
	ld	e, (hl)
	inc	hl
	ld	d, (hl)
	ret
1$:	ld	a, (SCUR)
	ld	b, #5			; octave shift = 5 - pitch / 48
2$:	cp	#48
	jr	c, 3$
	sub	#48
	dec	b
	jr	2$
3$:	add	a, a
	ld	e, a
	ld	d, #0
	ld	hl, #ptab
	add	hl, de
	ld	e, (hl)
	inc	hl
	ld	d, (hl)
	inc	b
	jr	5$
4$:	srl	d
	rr	e
5$:	djnz	4$
	ret
""")
w("nrate:\t.dw\t%s" % ", ".join(str(inc(p)) for p in (200, 150, 100, 150)))
w("; increments of pitches 240-287")
for i in range(0, 48, 12):
    w("%s\t.dw\t%s" % ("ptab:" if i == 0 else "", ", ".join(str(v) for v in TOP[i:i + 12])))
open(out, "w").write("\n".join(lines) + "\n")
print("sound: fs = %.0f Hz, block = %d T, FRAC = %d" % (FS, BLOCK_T, FRAC))
