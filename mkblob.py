#!/usr/bin/env python3
# Turns the linked SMFS code (smfs.s: absolute parts for RAM) into a page-2 module: the bytes of each part, the
# routine fscopy that copies them to their places, and the addresses fs.s uses. Fails if a part leaves its RAM.
# Usage: mkblob.py shared.inc out/smfs.ihx out/smfs.map out/smblob.s
# Copyright (C) 2026 Santiago Crespo
# SPDX-License-Identifier: 0BSD
import re
import sys

inc, ihx, mapf, out = sys.argv[1:5]
sym = {}
for m in re.finditer(r"^(\w+)\s*=\s*([^;\n]+)", open(inc).read(), re.M):
    try:
        sym[m.group(1)] = eval(m.group(2), {}, sym)
    except (NameError, SyntaxError):
        pass
mem = {}
for line in open(ihx):
    n, addr = int(line[1:3], 16), int(line[3:7], 16)
    if line[7:9] == "00":
        for i, b in enumerate(bytes.fromhex(line[9:9 + 2 * n])):
            mem[addr + i] = b
bases = [("SMA", sym["SMCODE"], sym["SMA_END"]),
         ("SMC", sym["SMC"], sym["SMC_END"]), ("SMD", sym["SMD"], sym["SMD_END"]),
         ("SME", sym["SME"], sym["SME_END"])]
parts = []
for name, lo, hi in bases:
    mine = [a for a in mem if a >= lo and not any(lo < l2 <= a for _, l2, _ in bases)]
    top = max(mine) + 1 if mine else lo
    if top > hi:
        sys.exit("%s: %d bytes, %d too many (%04X-%04X)" % (name, top - lo, top - hi, lo, hi))
    parts.append((name, lo, bytes(mem.get(a, 0) for a in range(lo, top)), hi - lo))
claimed = set(a for _, lo, b, _ in parts for a in range(lo, lo + len(b)))
if set(mem) - claimed:
    sys.exit("bytes outside the parts: %04X" % min(set(mem) - claimed))
glob = dict((m.group(2), int(m.group(1), 16))
            for m in re.finditer(r"\b([0-9A-F]{8})\s+([A-Za-z_]\w*)", open(mapf).read()))
o = ["; Generated by mkblob.py from %s. Do not edit." % ihx, "\t.area\tP2"]
for n in ("SMENTRY", "crcup", "m_crc"):
    o.append("%s == 0x%04X" % (n, glob[n]))
o += ["; Copies the SMFS code to RAM. Destroys B,C,D,E,H,L,F.", "fscopy::", "\tld\thl, #smimg"]
for name, lo, b, room in parts:
    o += ["\tld\tde, #0x%04X\t; %s: %d of %d bytes" % (lo, name, len(b), room), "\tld\tbc, #%d" % len(b), "\tldir"]
o += ["\tret", "smimg:"]
for name, lo, b, room in parts:
    o += ["\t.db\t" + ",".join("0x%02X" % x for x in b[i:i + 16]) for i in range(0, len(b), 16)]
open(out, "w").write("\n".join(o) + "\n")
print("SMFS code: " + ", ".join("%s %d of %d" % (n, len(b), r) for n, _, b, r in parts) +
      "; %d bytes in all" % sum(len(b) for _, _, b, _ in parts))
